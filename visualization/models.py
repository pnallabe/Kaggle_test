"""Database Models for Visualization and Dashboard Management

This module contains SQLAlchemy models for storing visualization metadata,
dashboard configurations, insight narratives, and user preferences.
"""

from sqlalchemy import (
    Column, Integer, String, Text, DateTime, Boolean, Float, 
    JSON, ForeignKey, Index, UniqueConstraint, CheckConstraint,
    Enum, LargeBinary, Table
)
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship, backref
from sqlalchemy.dialects.postgresql import UUID, JSONB, ARRAY
from sqlalchemy.sql import func
from datetime import datetime
from typing import Dict, List, Optional, Any
import uuid
import enum

# Create base class
Base = declarative_base()


# Enums for model fields
class ChartType(enum.Enum):
    """Chart types supported by the visualization system."""
    BAR = "bar"
    LINE = "line"
    SCATTER = "scatter"
    PIE = "pie"
    HISTOGRAM = "histogram"
    BOX = "box"
    HEATMAP = "heatmap"
    AREA = "area"
    TREEMAP = "treemap"
    TABLE = "table"
    GAUGE = "gauge"
    FUNNEL = "funnel"


class DashboardType(enum.Enum):
    """Dashboard types for different use cases."""
    EXECUTIVE = "executive"
    OPERATIONAL = "operational"
    ANALYTICAL = "analytical"
    KPI = "kpi"
    CUSTOM = "custom"


class InsightType(enum.Enum):
    """Types of insights generated by AI."""
    TREND = "trend"
    ANOMALY = "anomaly"
    CORRELATION = "correlation"
    DISTRIBUTION = "distribution"
    COMPARISON = "comparison"
    FORECAST = "forecast"
    SUMMARY = "summary"
    RECOMMENDATION = "recommendation"


class VisualizationStatus(enum.Enum):
    """Status of visualization generation."""
    PENDING = "pending"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"
    CACHED = "cached"


class ShareLevel(enum.Enum):
    """Sharing levels for dashboards and visualizations."""
    PRIVATE = "private"
    TEAM = "team"
    ORGANIZATION = "organization"
    PUBLIC = "public"


# Association table for many-to-many relationships
dashboard_charts = Table(
    'dashboard_charts',
    Base.metadata,
    Column('dashboard_id', UUID(as_uuid=True), ForeignKey('dashboards.id'), primary_key=True),
    Column('chart_id', UUID(as_uuid=True), ForeignKey('charts.id'), primary_key=True),
    Column('position_x', Integer, default=0),
    Column('position_y', Integer, default=0),
    Column('width', Integer, default=400),
    Column('height', Integer, default=300),
    Column('created_at', DateTime(timezone=True), server_default=func.now())
)

user_dashboard_favorites = Table(
    'user_dashboard_favorites',
    Base.metadata,
    Column('user_id', String(255), primary_key=True),
    Column('dashboard_id', UUID(as_uuid=True), ForeignKey('dashboards.id'), primary_key=True),
    Column('created_at', DateTime(timezone=True), server_default=func.now())
)


class User(Base):
    """User model for authentication and preferences."""
    __tablename__ = 'users'
    
    id = Column(String(255), primary_key=True)
    email = Column(String(255), unique=True, nullable=False, index=True)
    name = Column(String(255), nullable=False)
    role = Column(String(50), default='analyst')
    preferences = Column(JSONB, default=dict)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    last_login = Column(DateTime(timezone=True))
    is_active = Column(Boolean, default=True)
    
    # Relationships
    charts = relationship("Chart", back_populates="creator", cascade="all, delete-orphan")
    dashboards = relationship("Dashboard", back_populates="creator", cascade="all, delete-orphan")
    insights = relationship("InsightNarrative", back_populates="creator", cascade="all, delete-orphan")
    favorite_dashboards = relationship(
        "Dashboard", 
        secondary=user_dashboard_favorites, 
        back_populates="favorited_by"
    )
    
    # Indexes
    __table_args__ = (
        Index('idx_users_email', 'email'),
        Index('idx_users_active', 'is_active'),
    )
    
    def __repr__(self):
        return f"<User(id='{self.id}', email='{self.email}')>"


class DataSource(Base):
    """Data source configuration for charts and dashboards."""
    __tablename__ = 'data_sources'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    name = Column(String(255), nullable=False)
    source_type = Column(String(50), nullable=False)  # 'bigquery', 'csv', 'api', etc.
    connection_params = Column(JSONB, nullable=False)
    schema_info = Column(JSONB, default=dict)
    refresh_schedule = Column(String(100))  # Cron expression
    last_refresh = Column(DateTime(timezone=True))
    cache_duration = Column(Integer, default=3600)  # seconds
    is_active = Column(Boolean, default=True)
    created_by = Column(String(255), ForeignKey('users.id'))
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    charts = relationship("Chart", back_populates="data_source")
    
    # Indexes
    __table_args__ = (
        Index('idx_data_sources_type', 'source_type'),
        Index('idx_data_sources_active', 'is_active'),
    )
    
    def __repr__(self):
        return f"<DataSource(id='{self.id}', name='{self.name}', type='{self.source_type}')>"


class Chart(Base):
    """Individual chart/visualization configuration."""
    __tablename__ = 'charts'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    title = Column(String(255), nullable=False)
    description = Column(Text)
    chart_type = Column(Enum(ChartType), nullable=False)
    
    # Chart configuration
    config = Column(JSONB, nullable=False)  # Plotly/chart-specific config
    data_query = Column(Text)  # SQL query or data retrieval logic
    data_source_id = Column(UUID(as_uuid=True), ForeignKey('data_sources.id'))
    
    # Styling and layout
    styling = Column(JSONB, default=dict)
    layout_config = Column(JSONB, default=dict)
    color_scheme = Column(String(50), default='default')
    
    # Generation metadata
    generated_from_query = Column(Text)  # Original natural language query
    ai_confidence_score = Column(Float)  # Confidence in AI-generated chart
    generation_metadata = Column(JSONB, default=dict)
    
    # Status and caching
    status = Column(Enum(VisualizationStatus), default=VisualizationStatus.PENDING)
    cache_key = Column(String(255), index=True)
    last_rendered = Column(DateTime(timezone=True))
    render_time_ms = Column(Integer)  # Rendering performance metric
    
    # Sharing and permissions
    share_level = Column(Enum(ShareLevel), default=ShareLevel.PRIVATE)
    shared_with = Column(ARRAY(String), default=list)  # User IDs with access
    
    # Audit fields
    created_by = Column(String(255), ForeignKey('users.id'), nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    version = Column(Integer, default=1)
    
    # Usage statistics
    view_count = Column(Integer, default=0)
    last_viewed = Column(DateTime(timezone=True))
    export_count = Column(Integer, default=0)
    
    # Relationships
    creator = relationship("User", back_populates="charts")
    data_source = relationship("DataSource", back_populates="charts")
    dashboards = relationship("Dashboard", secondary=dashboard_charts, back_populates="charts")
    versions = relationship("ChartVersion", back_populates="chart", cascade="all, delete-orphan")
    
    # Indexes
    __table_args__ = (
        Index('idx_charts_creator', 'created_by'),
        Index('idx_charts_type', 'chart_type'),
        Index('idx_charts_status', 'status'),
        Index('idx_charts_share_level', 'share_level'),
        Index('idx_charts_cache_key', 'cache_key'),
        Index('idx_charts_created_at', 'created_at'),
    )
    
    def __repr__(self):
        return f"<Chart(id='{self.id}', title='{self.title}', type='{self.chart_type}')>"


class ChartVersion(Base):
    """Version history for charts."""
    __tablename__ = 'chart_versions'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    chart_id = Column(UUID(as_uuid=True), ForeignKey('charts.id'), nullable=False)
    version_number = Column(Integer, nullable=False)
    
    # Snapshot of chart configuration
    config_snapshot = Column(JSONB, nullable=False)
    styling_snapshot = Column(JSONB, default=dict)
    query_snapshot = Column(Text)
    
    # Version metadata
    change_summary = Column(Text)
    changed_by = Column(String(255), ForeignKey('users.id'))
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    
    # Relationships
    chart = relationship("Chart", back_populates="versions")
    
    # Constraints
    __table_args__ = (
        UniqueConstraint('chart_id', 'version_number', name='uq_chart_version'),
        Index('idx_chart_versions_chart', 'chart_id'),
    )
    
    def __repr__(self):
        return f"<ChartVersion(chart_id='{self.chart_id}', version={self.version_number})>"


class Dashboard(Base):
    """Dashboard containing multiple charts and configurations."""
    __tablename__ = 'dashboards'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    title = Column(String(255), nullable=False)
    description = Column(Text)
    dashboard_type = Column(Enum(DashboardType), default=DashboardType.CUSTOM)
    
    # Dashboard configuration
    layout_config = Column(JSONB, nullable=False)  # Grid layout, dimensions, etc.
    theme_config = Column(JSONB, default=dict)  # Colors, fonts, styling
    filter_config = Column(JSONB, default=dict)  # Global filters
    
    # Generated dashboard metadata
    generated_from_query = Column(Text)  # Original query that generated this dashboard
    template_id = Column(String(100))  # Template used for generation
    ai_confidence_score = Column(Float)
    generation_metadata = Column(JSONB, default=dict)
    
    # Looker Studio integration
    looker_dashboard_id = Column(String(255), unique=True)
    looker_embed_url = Column(Text)
    looker_edit_url = Column(Text)
    
    # Status and performance
    status = Column(Enum(VisualizationStatus), default=VisualizationStatus.PENDING)
    last_refreshed = Column(DateTime(timezone=True))
    refresh_duration_ms = Column(Integer)
    
    # Sharing and permissions
    share_level = Column(Enum(ShareLevel), default=ShareLevel.PRIVATE)
    shared_with = Column(ARRAY(String), default=list)
    embed_token = Column(String(255), unique=True)  # For public embedding
    
    # Audit fields
    created_by = Column(String(255), ForeignKey('users.id'), nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Usage statistics
    view_count = Column(Integer, default=0)
    last_viewed = Column(DateTime(timezone=True))
    favorite_count = Column(Integer, default=0)
    
    # Relationships
    creator = relationship("User", back_populates="dashboards")
    charts = relationship("Chart", secondary=dashboard_charts, back_populates="dashboards")
    favorited_by = relationship("User", secondary=user_dashboard_favorites, back_populates="favorite_dashboards")
    
    # Indexes
    __table_args__ = (
        Index('idx_dashboards_creator', 'created_by'),
        Index('idx_dashboards_type', 'dashboard_type'),
        Index('idx_dashboards_status', 'status'),
        Index('idx_dashboards_share_level', 'share_level'),
        Index('idx_dashboards_created_at', 'created_at'),
        Index('idx_dashboards_looker_id', 'looker_dashboard_id'),
    )
    
    def __repr__(self):
        return f"<Dashboard(id='{self.id}', title='{self.title}', type='{self.dashboard_type}')>"


