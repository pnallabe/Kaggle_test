class AuditLog(Base):
    """Audit log for tracking user actions and system events."""
    __tablename__ = 'audit_logs'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    
    # Event details
    event_type = Column(String(50), nullable=False)  # CREATE, UPDATE, DELETE, VIEW, SHARE
    resource_type = Column(String(50), nullable=False)  # chart, dashboard, insight
    resource_id = Column(String(255), nullable=False)
    
    # User and session
    user_id = Column(String(255), ForeignKey('users.id'))
    session_id = Column(String(255))
    ip_address = Column(String(45))  # IPv6 compatible
    user_agent = Column(Text)
    
    # Event data
    event_data = Column(JSONB, default=dict)  # Additional event-specific data
    old_values = Column(JSONB, default=dict)  # For UPDATE events
    new_values = Column(JSONB, default=dict)  # For UPDATE events
    
    # Result
    success = Column(Boolean, default=True)
    error_message = Column(Text)
    
    # Timestamp
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    
    # Indexes
    __table_args__ = (
        Index('idx_audit_logs_user', 'user_id'),
        Index('idx_audit_logs_resource', 'resource_type', 'resource_id'),
        Index('idx_audit_logs_event', 'event_type'),
        Index('idx_audit_logs_created', 'created_at'),
        Index('idx_audit_logs_session', 'session_id'),
    )
    
    def __repr__(self):
        return f"<AuditLog(event='{self.event_type}', resource='{self.resource_type}:{self.resource_id}')>"


# Database utility functions
def create_tables(engine):
    """Create all tables in the database.
    
    Args:
        engine: SQLAlchemy engine instance
    """
    Base.metadata.create_all(bind=engine)


def drop_tables(engine):
    """Drop all tables from the database.
    
    Args:
        engine: SQLAlchemy engine instance
    """
    Base.metadata.drop_all(bind=engine)


