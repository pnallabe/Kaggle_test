class QueryCache(Base):
    """Cache for expensive query results and computations."""
    __tablename__ = 'query_cache'
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    cache_key = Column(String(255), unique=True, nullable=False, index=True)
    query_hash = Column(String(64), nullable=False, index=True)  # Hash of SQL query
    
    # Cached data
    result_data = Column(LargeBinary)  # Pickled/compressed result data
    result_metadata = Column(JSONB, default=dict)  # Schema, row count, etc.
    
    # Cache configuration
    ttl_seconds = Column(Integer, default=3600)
    cache_level = Column(String(50), default='session')  # temporary, session, persistent
    
    # Performance metrics
    original_query_time_ms = Column(Integer)
    data_size_bytes = Column(Integer)
    compression_ratio = Column(Float)
    
    # Usage tracking
    hit_count = Column(Integer, default=0)
    last_accessed = Column(DateTime(timezone=True))
    
    # Audit fields
    created_by = Column(String(255), ForeignKey('users.id'))
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    expires_at = Column(DateTime(timezone=True), nullable=False)
    
    # Indexes
    __table_args__ = (
        Index('idx_query_cache_key', 'cache_key'),
        Index('idx_query_cache_hash', 'query_hash'),
        Index('idx_query_cache_expires', 'expires_at'),
        Index('idx_query_cache_created', 'created_at'),
    )
    
    def __repr__(self):
        return f"<QueryCache(cache_key='{self.cache_key}', expires_at='{self.expires_at}')>"


